    private void SpawnWildlife()
    {
        if (_wildProps.Count > 0 && _wildProps.All(p => p.IsValid)) return;
        foreach (var p in _wildProps) if (p.IsValid) p.Remove();
        _wildProps.Clear();
        foreach (var w in Wildlife)
        {
            try
            {
                var p = Utilities.CreateEntityByName<CDynamicProp>("prop_dynamic");
                if (p == null) continue;
                p.Collision.SolidType = SolidType_t.SOLID_NONE;
                p.DispatchSpawn();
                p.SetModel(WildPath(w.Model));
                p.Teleport(new Vector(w.X, w.Y, w.Model.Contains("fish") ? w.Z - 20 : w.Z), new QAngle(0, w.Yaw, 0), null);
                SetPropScale(p, w.Scale);
                p.AcceptInput("SetAnimation", null, null, "idle");
                p.AcceptInput("SetDefaultAnimation", null, null, "idle");
                _wildProps.Add(p);
            }
            catch { }
        }
    }
