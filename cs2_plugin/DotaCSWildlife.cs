    private static string WildPath(string n) => $"models/dota_wild/{n}/{n}.vmdl";

    private static void PrecacheWildlife(ResourceManifest m)
    {
        foreach (var n in Wildlife.Select(w => w.Model).Distinct()) m.AddResource(WildPath(n));
