    private CDynamicProp? SpawnStatic(string path, float x, float y, float z, float yaw, float scale, bool solid, string? anim)
    {
        var p = Utilities.CreateEntityByName<CDynamicProp>("prop_dynamic");
        if (p == null) return null;
        p.Collision.SolidType = solid ? SolidType_t.SOLID_VPHYSICS : SolidType_t.SOLID_NONE;
        p.DispatchSpawn();
        p.SetModel(path);
        p.Teleport(new Vector(x, y, z), new QAngle(0, yaw, 0), null);
        if (Math.Abs(scale - 1f) > 0.01f) SetPropScale(p, scale);
        if (anim != null) { p.AcceptInput("SetAnimation", null, null, anim); p.AcceptInput("SetDefaultAnimation", null, null, anim); }
        return p;
    }

