            var cut = now < _treeCutUntil[i];
            var t = Trees[i];
            if (!cut && (_treeProps[i] == null || !_treeProps[i]!.IsValid))
            {
                try { _treeProps[i] = SpawnStatic(DynPath(t.Model), t.X, t.Y, t.Z, t.Yaw, t.Scale, true, null); } catch { }
                if (_stumpProps[i] != null && _stumpProps[i]!.IsValid) _stumpProps[i]!.Remove();
                _stumpProps[i] = null;
                budget--;
            }
        }
        _treeSpawnCursor = (_treeSpawnCursor + 150) % Trees.Length;

        if (_decorProps.Count == 0)
            foreach (var d in Decor)
                try
                {
                    var p = SpawnStatic(DynPath(d.Model), d.X, d.Y, d.Z, d.Yaw, d.Scale, false, "idle");
                    if (p != null) _decorProps.Add(p);
                }
                catch { }
    }

    // a tree was cut in Dota (or blown up in CS): remove it, leave a stump
    private void CutTree(float x, float y)
    {
        if (!TreesAsProps) return;
        var best = -1; var bestD = 90f * 90f;
        for (var i = 0; i < Trees.Length; i++)
        {
            var dx = Trees[i].X - x; var dy = Trees[i].Y - y; var d = dx * dx + dy * dy;
            if (d < bestD) { bestD = d; best = i; }
        }
        Logger.LogInformation("DotaCS tree cut at {X} {Y}: nearest tree {Best} at {D} units", x, y, best, Math.Sqrt(bestD));
        if (best < 0) return;
        _treeCutUntil[best] = Server.CurrentTime + TreeRegrowSeconds;
        var tp = _treeProps[best];
        if (tp != null && tp.IsValid) tp.Remove();
        _treeProps[best] = null;
        var t = Trees[best];
        try { _stumpProps[best] = SpawnStatic($"models/dota_dyn/{t.Model}/{t.Model}_stump.vmdl", t.X, t.Y, t.Z, t.Yaw, t.Scale, false, null); } catch { }
        PlayDotaSound("Ambient.TreeFall", new Vector(t.X, t.Y, t.Z + 50));
    }

