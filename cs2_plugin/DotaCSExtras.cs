    private void UpdateLights(List<CCSPlayerController> humans)
    {
        var now = Server.CurrentTime;
        if (now - _lastLightTick < 1f) return;
        _lastLightTick = now;
        var players = humans.Select(p => p.PlayerPawn.Value?.AbsOrigin).Where(p => p != null).Select(p => p!).ToList();
        if (players.Count == 0) return;

        var wanted = new HashSet<int>(DotaLights
            .Select((l, i) => (i, d: players.Min(p => Dist2(l.X, l.Y, p))))
            .Where(x => x.d < LightRange).OrderBy(x => x.d).Take(MaxLights).Select(x => x.i));

        foreach (var i in _lights.Keys.ToList())
            if (!wanted.Contains(i)) { if (_lights[i].IsValid) _lights[i].Remove(); _lights.Remove(i); }

        foreach (var i in wanted)
        {
            if (_lights.TryGetValue(i, out var have) && have.IsValid) continue;
            try
            {
                var l = DotaLights[i];
                var e = Utilities.CreateEntityByName<COmniLight>("light_omni2");
                if (e == null) continue;
                e.Color = System.Drawing.Color.FromArgb(255, l.Cr, l.Cg, l.Cb);
                e.Brightness = Math.Clamp(l.I * 0.35f, 0.5f, 4f);
                e.Range = Math.Max(l.R * 2.2f, 150f);
                e.CastShadows = 0;
                e.Enabled = true;
                e.DispatchSpawn();
                e.Teleport(new Vector(l.X, l.Y, l.Z), null, null);
                _lights[i] = e;
            }
            catch { }
        }
    }

