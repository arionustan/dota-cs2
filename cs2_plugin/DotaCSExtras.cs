    // ------------------------------------------------------------ shooting creeps, neutrals and Roshan
    // bullets fly through Dota units (they have no hitbox in CS), so test the shot line against a cylinder per unit
    private bool TryHitUnit(CCSPlayerController shooter, float x, float y, float z, float dmg, string weapon)
    {
        var pawn = shooter.PlayerPawn.Value;
        var o = pawn?.AbsOrigin;
        if (pawn == null || o == null) return false;
        float sx = o.X, sy = o.Y, sz = o.Z + 64f;
        float dx = x - sx, dy = y - sy, dz = z - sz;
        var dxy = dx * dx + dy * dy;
        if (dxy < 1f) return false;
        UnitState? best = null; var bestT = 2f; var hitP = new Vector(0, 0, 0);
        foreach (var u in _units.Values)
        {
            if (!u.Alive) continue;
            var (r, h) = UnitHitbox.TryGetValue(u.Model, out var hb) ? hb : (32f, 95f);
            r = Math.Max(r * 1.5f, 34f); h = Math.Max(h * 1.3f, 90f);   // generous: Dota units move between updates, CS players expect forgiving hits
            var t = Math.Clamp(((u.X - sx) * dx + (u.Y - sy) * dy) / dxy, 0f, 1.02f);
            float px = sx + dx * t, py = sy + dy * t, pz = sz + dz * t;
            var ddx = px - u.X; var ddy = py - u.Y;
            if (ddx * ddx + ddy * ddy > r * r || pz < u.Z - 25 || pz > u.Z + h) continue;
            if (t < bestT) { bestT = t; best = u; hitP = new Vector(px, py, pz); }
        }
        if (best == null) return false;
        _hits.Enqueue(string.Format(Inv, "D {0} {1} {2} {3}", best.Id, dmg * DmgMult(shooter.Slot), shooter.Slot, weapon));
        Blood(hitP, new Vector(dx, dy, dz));
        return true;
    }

    // CS2 blood: a spray in the direction of the shot plus a splat on the ground
    private static readonly string[] BloodFx =
    {
        "particles/blood_impact/blood_impact_high.vpcf",
        "particles/blood_impact/blood_impact_high_vis_spray.vpcf",
        "particles/blood_impact/blood_impact_high_ground_decal.vpcf",
    };

    private void Blood(Vector at, Vector? dir = null)
    {
        var yaw = 0f; var pitch = 0f;
        if (dir != null)
        {
            yaw = (float)(Math.Atan2(dir.Y, dir.X) * 180 / Math.PI);
            pitch = (float)(-Math.Atan2(dir.Z, Math.Sqrt(dir.X * dir.X + dir.Y * dir.Y)) * 180 / Math.PI);
        }
        foreach (var name in BloodFx)
        {
            try
            {
                var fx = Utilities.CreateEntityByName<CParticleSystem>("info_particle_system");
                if (fx == null) continue;
                fx.EffectName = name;
                fx.StartActive = true;
                fx.DispatchSpawn();
                fx.Teleport(at, new QAngle(pitch, yaw, 0), null);
                fx.AcceptInput("Start");
                AddTimer(3f, () => { if (fx.IsValid) fx.Remove(); });
            }
            catch { }
        }
    }

    // ------------------------------------------------------------ footsteps of Dota units near CS players
    private readonly Dictionary<string, float> _nextStep = new();

    private void UpdateFootsteps(List<CCSPlayerController> humans)
    {
        var now = Server.CurrentTime;
        var players = humans.Select(p => p.PlayerPawn.Value?.AbsOrigin).Where(p => p != null).Select(p => p!).ToList();
        if (players.Count == 0) return;
        void Step(string id, float x, float y, float z, string ev, float every)
        {
            if (_nextStep.TryGetValue(id, out var t) && now < t) return;
            if (players.Min(p => Dist2(x, y, p)) > 1200) return;
            _nextStep[id] = now + every;
            PlayDotaSound(ev, new Vector(x, y, z));
        }
        foreach (var h in _heroes.Values)
            if (h.Alive && _heroMoveTime.TryGetValue(h.Id, out var mt) && now - mt < 0.25f)
                Step("h" + h.Id, h.X, h.Y, h.Z, h.Name == "pudge" ? "Hero_Pudge.Footsteps" : "n_creep_General.Footstep", 0.38f);
        foreach (var u in _units.Values)
        {
            if (!u.Alive || !_unitMoveTime.TryGetValue(u.Id, out var mt) || now - mt > 0.25f) continue;
            var ev = u.Model == "roshan" ? "Roshan.Footstep"
                : u.Model.StartsWith("radiant") || u.Model.Contains("good") ? "Creep_Radiant.Footstep"
                : u.Model.StartsWith("lane_dire") || u.Model.Contains("bad") ? "Creep_Dire.Footstep"
                : u.Model.Contains("lrg") || u.Model.Contains("big") || u.Model.Contains("dragon") || u.Model.Contains("golem") ? "n_creep_Giant.Footstep"
                : "n_creep_General.Footstep";
            Step("u" + u.Id, u.X, u.Y, u.Z, ev, 0.42f);
        }
    }
